def build_lut():
    # 生成 256 项查找表，未定义字符用空格（0）填充
    lut = {}
    for code in range(256):
        ch = chr(code)
        if ch in FONT:
            lut[code] = FONT[ch]
        else:
            lut[code] = [0x00]*16
    return lut

def emit(path):
    lut = build_lut()
    lines = []
    lines.append("// =====================================================================")
    lines.append("// osd_font.v : 8x16 ASCII 字模 ROM（由脚本生成，勿手改）")
    lines.append("// 包含：空格 / ':' '/' '0'-'9' 'A'-'Z'，其余字符为空白")
    lines.append("// 行索引 = ASCII 码(0-255)，每行 16 字节，bit7=最左列，bit=1 点亮")
    lines.append("// =====================================================================")
    lines.append("")
    lines.append("// 8x16 字模：function 形式，供 OSD 按 ascii/row 查表")
    lines.append("// 数据以 16 进制数组表示，避免综合器对 2D 数组支持问题")
    lines.append("function [7:0] osd_font_row;")
    lines.append("    input [7:0] ascii;")
    lines.append("    input [3:0] row;")
    lines.append("    reg [15:0] glyph;    // 16行*8bit 需 128bit，分两次查，这里逐行用 case")
    lines.append("begin")
    lines.append("    case ({ascii, row})")
    for code in sorted(lut.keys()):
        g = lut[code]
        for r in range(16):
            lines.append(f"        12'h{code:02X}{r:X}: osd_font_row = 8'h{g[r]:02X};")
    lines.append("        default: osd_font_row = 8'h00;")
    lines.append("    endcase")
    lines.append("end")
    lines.append("endfunction")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"written {path}, {len(lut)} glyphs")

