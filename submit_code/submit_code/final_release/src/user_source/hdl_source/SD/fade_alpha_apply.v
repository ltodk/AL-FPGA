`timescale 1ns/1ps
// -----------------------------------------------------------------------------
// fade_alpha_apply —— 转场像素处理：淡到灰（fade through grey）
//
//   y = (x * g + FADE_GRAY * (256 - g)) >> 8 ,   g = alpha + 1 ∈ [1, 256]
//
// ★ 为什么不是"乘性压暗"（上一版的 y = x*(alpha+1)>>8）
//   alpha 是**编码域**的乘性系数，而显示器响应是 2.2 伽马：
//       编码值乘 0.25 → 实际发光只剩 0.25^2.2 ≈ 4.8%
//   实机验证：MIN_ALPHA 从 0 提到 64（编码 25%）仍觉得刺眼 —— 因为
//   4.8% 和 0% 在肉眼看来没有区别。乘性压暗要走"不刺眼"，得抬到
//   alpha=128（21.6%）甚至 160（35.9%），那时已经基本没有转场感了。
//
//   改成向灰阶收敛后，亮度**不下落**（暗图反而变亮，亮图缓慢降到灰阶），
//   全程没有暗谷 → 满足"不要刺眼"的诉求；而换 bank 发生的最糊那一帧是
//   "统一灰、无内容"，新图完全藏得住，比压暗时更不易露馅。
//
// ★ 两端精确
//   alpha = 255 → g = 256 → y = x                     逐位旁路，回归基线不变
//   alpha = 0   → g = 1   → y = (x + 255*GRAY) >> 8   落在 GRAY 附近（floor 误差 ≤1）
//   x = GRAY 时输出恒为 GRAY（不动点，与 alpha 无关）—— 可用于自检公式正确性。
//
// ★ 实现要点
//   纯组合、纯无符号，**不需要符号扩展和钳位**：结果是 x 与 GRAY 的加权平均，
//   必然落在 [min(x,GRAY), max(x,GRAY)] 内，数学上不可能溢出。
//   - 8bit × 9bit 最大 255*256 = 65280，17 bit 足够；
//   - 两个乘积相加 18 bit，取 [15:8] 即 >>8；
//   - 像素时钟仅 25MHz（40ns），组合乘法无时序压力；
//   - 组合实现「零延迟」，de/vs/video_x 无需再延迟，下游 OSD/字幕坐标一像素都不用改。
//   若将来提到 148.5MHz（1080p），这里必须改成 1 级流水并同步延迟 de/vs/x。
// -----------------------------------------------------------------------------
module fade_alpha_apply #(
    // 转场最"糊"时的目标灰阶。128 = 中性灰（第14讲把对比度调到 C=0 时的那一屏）。
    //   128 → 中性灰，白字 OSD 仍清晰（推荐）
    //   176 → 发雾、更柔，但 OSD 白字会开始糊
    //   224 → 接近"白闪"，最柔，但 OSD 白字在最糊那一帧基本看不见
    parameter integer FADE_GRAY = 128
)(
    input  wire [7:0]  alpha,     // 255 = 原图（逐位旁路）；MIN_ALPHA = 最糊（几乎全灰）
    input  wire [23:0] rgb_in,
    output wire [23:0] rgb_out
);

    localparam [7:0] GRAY_C = FADE_GRAY;

    // 原图权重 1~256（9 bit）。用 (alpha+1) 让 alpha=255 时逐位旁路
    wire [8:0] g  = {1'b0, alpha} + 9'd1;
    // 灰幕权重 0~255：g=256 时 ig=0（纯原图），g=1 时 ig=255（几乎纯灰）
    wire [8:0] ig = 9'd256 - g;

    // 8bit x 9bit 最大 255*256 = 65280，17 bit 足够
    wire [16:0] mul_r = {9'd0, rgb_in[23:16]} * g;
    wire [16:0] mul_g = {9'd0, rgb_in[15:8]}  * g;
    wire [16:0] mul_b = {9'd0, rgb_in[7:0]}   * g;

    // 灰幕分量：三通道相同，只算一次
    wire [16:0] gry   = {9'd0, GRAY_C} * ig;

    // 求和后 >>8：最大 255*256 = 65280（g=256 时 gry=0），18 bit 足够
    wire [17:0] sum_r = {1'b0, mul_r} + {1'b0, gry};
    wire [17:0] sum_g = {1'b0, mul_g} + {1'b0, gry};
    wire [17:0] sum_b = {1'b0, mul_b} + {1'b0, gry};

    // 取 [15:8] 即 >>8
    assign rgb_out = {sum_r[15:8], sum_g[15:8], sum_b[15:8]};

endmodule
